using KiriChess.Server.Data;
using KiriChess.Server.Data.Entities;
using Microsoft.EntityFrameworkCore;

namespace KiriChess.Server.Infrastructure.Push;

/// <summary>
/// Reads and writes <see cref="WebPushSubscription"/> rows (11b.1 follow-up). Scoped, like
/// <c>NotificationPreferenceService</c>: it takes a <c>KiriChessDbContext</c> directly and is only
/// ever called from a request handler.
/// </summary>
public sealed class PushSubscriptionService
{
    private readonly KiriChessDbContext _db;

    public PushSubscriptionService(KiriChessDbContext db) => _db = db;

    /// <summary>
    /// Upserts by <see cref="WebPushSubscription.Endpoint"/>, not by (user, endpoint): the browser
    /// hands back the same endpoint on re-subscription, and a shared/reinstalled browser handing that
    /// endpoint to a different signed-in account should move the row to them, not create a duplicate
    /// that the unique index would reject anyway.
    ///
    /// S-1-14: this re-keying is a deliberate, accepted trade, not an oversight, and the security
    /// consequence is worth stating rather than leaving implicit. `L-2` calls a push endpoint URL a
    /// capability: whoever presents it owns the row. An attacker who obtains a victim's endpoint (it is
    /// never returned by any read endpoint, and is high-entropy, so this is a narrow exposure) can move
    /// the subscription to their own account, silently stopping the victim's notifications and making
    /// the victim's browser show notifications generated by the attacker's games. If cheaply possible
    /// later, requiring the new `p256dh`/`auth` pair to differ from the stored one before re-keying
    /// would catch a bare replay of a copied row without giving up the shared-browser re-subscribe case
    /// this method exists for.
    /// </summary>
    public async Task SubscribeAsync(Guid userId, string endpoint, string p256dh, string auth, CancellationToken ct = default)
    {
        var existing = await _db.WebPushSubscriptions.FirstOrDefaultAsync(s => s.Endpoint == endpoint, ct);
        if (existing is not null)
        {
            existing.UserId = userId;
            existing.P256dh = p256dh;
            existing.Auth = auth;
        }
        else
        {
            _db.WebPushSubscriptions.Add(new WebPushSubscription
            {
                Id = Guid.NewGuid(),
                UserId = userId,
                Endpoint = endpoint,
                P256dh = p256dh,
                Auth = auth,
            });
        }
        await _db.SaveChangesAsync(ct);
    }

    /// <summary>
    /// No-oracle shape, same as <c>/api/account/sessions/{id}</c>: succeeds whether the endpoint
    /// existed, was already removed, or belonged to someone else - scoped to <paramref name="userId"/>
    /// so a guessed endpoint can never unsubscribe another account's device.
    /// </summary>
    public async Task UnsubscribeAsync(Guid userId, string endpoint, CancellationToken ct = default)
    {
        await _db.WebPushSubscriptions
            .Where(s => s.UserId == userId && s.Endpoint == endpoint)
            .ExecuteDeleteAsync(ct);
    }
}
